// Reproducible backtest report:  npm run backtest
// Writes backtest/RESULTS.md. Refresh the data first with: npm run backtest:fetch
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadCandles, loadFunding } from './data';
import { runBacktest, computeStats, type BacktestOptions, type BacktestResult } from './engine';
import { targetExposure, sma, DEFAULT_TREND_CONFIG, type TrendConfig } from '../lib/strategy/trend';
import { REBALANCE_BAND } from '../lib/strategy/rebalance';
import { researchMarkdown } from './report-research';

const candles = loadCandles();
const closes = candles.map(c => c.close);
const lastDate = candles[candles.length - 1].date;

const FULL = '2014-01-01';
const SPLIT = '2020-01-01';

interface Scenario { fundingMult?: number; slippage?: number; band?: number; noCosts?: boolean }

function options(start: string, end: string | undefined, s: Scenario = {}): BacktestOptions {
  return {
    startDate: start,
    endDate: end,
    rebalanceBand: s.band ?? REBALANCE_BAND,
    costs: {
      takerFee: s.noCosts ? 0 : 0.00045,
      slippage: s.noCosts ? 0 : s.slippage ?? 0.0003,
      fundingForDate: s.noCosts ? () => 0 : loadFunding(0.0003, s.fundingMult ?? 1),
      maintenanceMargin: 0.0125,
    },
  };
}

type Fn = (i: number) => number;
const trend = (cfg: Partial<TrendConfig> = {}, lagDays = 0): Fn => i =>
  targetExposure(closes, { ...DEFAULT_TREND_CONFIG, ...cfg }, i - 1 - lagDays).exposure;
const constant = (lev: number): Fn => () => lev;
const smaFilter = (n: number, lev: number): Fn => i => (closes[i - 1] > sma(closes, n, i - 1) ? lev : 0);

// Enters once at 1x and never rebalances (band is wide enough to ignore drift, narrow enough to allow the entry).
const HOLD: Scenario = { noCosts: true, band: 0.9 };

const pct = (x: number, d = 0) => `${(x * 100).toFixed(d)}%`;

function cells(r: BacktestResult): string[] {
  if (r.liquidated) return ['**liquidated**', r.liquidated, '', '-100%', '', '', ''];
  const s = computeStats(r);
  return [pct(s.cagr), s.sharpe.toFixed(2), pct(s.vol), pct(s.maxDrawdown), pct(s.worstYear), s.avgExposure.toFixed(2) + 'x', s.tradesPerYear.toFixed(0)];
}

const HEAD = '| Strategy | CAGR | Sharpe | Vol | Max drawdown | Worst year | Avg exposure | Trades/yr |\n|---|---|---|---|---|---|---|---|';

function table(rows: Array<[string, Fn, Scenario?]>, start: string, end?: string): string {
  return [HEAD, ...rows.map(([name, fn, sc]) => `| ${name} | ${cells(runBacktest(candles, fn, options(start, end, sc))).join(' | ')} |`)].join('\n');
}

const main: Array<[string, Fn, Scenario?]> = [
  ['Buy & hold spot (no leverage, no funding)', constant(1), HOLD],
  ['Perp held at constant 2x', constant(2), { band: 0.2 }],
  ['Perp held at constant 3x', constant(3), { band: 0.3 }],
  ['Perp held at constant 5x', constant(5), { band: 0.5 }],
  ['Long above 100-day SMA, 1x', smaFilter(100, 1)],
  ['Long above 100-day SMA, 3x', smaFilter(100, 3)],
  ['Long above 100-day SMA, 5x', smaFilter(100, 5)],
  ['**Vol-targeted trend, 40% vol, max 2x (default)**', trend()],
  ['Vol-targeted trend, 60% vol, max 2x', trend({ targetVol: 0.6 })],
  ['Vol-targeted trend, 80% vol, max 3x', trend({ targetVol: 0.8, maxLeverage: 3 })],
  ['Vol-targeted trend long/short, 40% vol, max 2x', trend({ allowShort: true })],
];

const robustness: Array<[string, Fn, Scenario?]> = [
  ['Default', trend()],
  ['SMAs 100 only', trend({ smaLookbacks: [100] })],
  ['SMAs 200 only', trend({ smaLookbacks: [200] })],
  ['SMAs 20/50/100', trend({ smaLookbacks: [20, 50, 100] })],
  ['SMAs 30/60/120/240', trend({ smaLookbacks: [30, 60, 120, 240] })],
  ['SMAs 100/200/300', trend({ smaLookbacks: [100, 200, 300] })],
  ['Vol lookback 14d', trend({ volLookback: 14 })],
  ['Vol lookback 60d', trend({ volLookback: 60 })],
  ['Vol lookback 90d', trend({ volLookback: 90 })],
  ['Rebalance band 0.10', trend(), { band: 0.1 }],
  ['Rebalance band 0.50', trend(), { band: 0.5 }],
  ['Funding cost doubled', trend(), { fundingMult: 2 }],
  ['Slippage 0.15% per trade (5x)', trend(), { slippage: 0.0015 }],
  ['Funding doubled + slippage 5x', trend(), { fundingMult: 2, slippage: 0.0015 }],
  ['Signal acted on 1 day late', trend({}, 1)],
  ['Signal acted on 3 days late', trend({}, 3)],
];

const def = runBacktest(candles, trend(), options(FULL, undefined));
const defStats = computeStats(def);
const hold = computeStats(runBacktest(candles, constant(1), options(FULL, undefined, HOLD)));
const years = Object.keys(defStats.byYear);
const live = targetExposure(closes, DEFAULT_TREND_CONFIG);

const md = `# BTC strategy backtest

Generated by \`npm run backtest\` from data through **${lastDate}**. Do not edit by hand.

**Nothing here is a guarantee.** A backtest shows how a rule would have done on
one historical path, and BTC's history is dominated by a single enormous bull
run. Read the losing years and the drawdown column before the CAGR column.

## Method

- **Data:** Bitstamp BTC/USD daily candles (${candles[0].date} → ${lastDate}); real Hyperliquid BTC funding from 2023-05-12, and an assumed 0.03%/day (≈11%/yr, paid by longs) before that.
- **Costs:** 0.045% taker fee + 0.03% slippage on every trade, plus funding every day a position is held.
- **No look-ahead:** the signal uses closes up to yesterday and trades at today's open.
- **Liquidation:** checked against each day's intraday low (high for shorts) with Hyperliquid's 1.25% BTC maintenance margin. A liquidation is recorded as losing the whole account.
- **Parameters were not optimised.** The default (50/100/150/200-day SMAs, 30-day vol, 40% target vol, 2x cap) was fixed before looking at results; the robustness table shows what happens when each choice is changed.
- **Out-of-sample:** 2014–2019 and 2020–${lastDate.slice(0, 4)} are reported separately. Nothing was fitted on either, but the second period is the fairer guide to what to expect.

## The strategy

Each day after the 00:00 UTC close:

1. **Trend score** = fraction of the 50/100/150/200-day moving averages the close is above (0, ¼, ½, ¾ or 1).
2. **Size** = trend score × (40% ÷ 30-day realised volatility), capped at 2x account equity. Calm uptrend → more than 1x; volatile or mixed trend → less; below all four averages → flat.
3. **Trade** only if the target differs from the current position by more than ${REBALANCE_BAND}x equity (or the target is flat).

Leverage here is a *result* of low volatility in an uptrend, not a fixed setting — that is what keeps it from being liquidated.

## Results: full period ${FULL} → ${lastDate}

${table(main, FULL)}

## Results: 2014–2019

${table(main, FULL, '2019-12-31')}

## Results: ${SPLIT} → ${lastDate}

${table(main, SPLIT)}

## Default strategy, year by year

| Year | ${years.join(' | ')} |
|---|${years.map(() => '---').join('|')}|
| Strategy | ${years.map(y => pct(defStats.byYear[y])).join(' | ')} |
| Buy & hold | ${years.map(y => pct(hold.byYear[y])).join(' | ')} |

Totals for the default over the full period: ${def.trades} trades, max exposure ${Math.max(...def.exposure).toFixed(2)}x, funding paid was ${(def.fundingPaid / def.feesPaid).toFixed(0)}x the trading fees — **funding, not fees, is the main cost of holding leveraged BTC longs.**

## Robustness: ${SPLIT} → ${lastDate}

Each row changes one thing about the default.

${table(robustness, SPLIT)}

## Robustness: full period

${table(robustness, FULL)}

## What the strategy would hold today

As of the ${lastDate} close: trend score ${live.trendScore.toFixed(2)}, 30-day volatility ${pct(live.vol)}, target exposure **${live.exposure.toFixed(2)}x**.
${researchMarkdown()}`;

writeFileSync(join(dirname(fileURLToPath(import.meta.url)), 'RESULTS.md'), md);
console.log(`wrote RESULTS.md (${md.length} chars)`);
